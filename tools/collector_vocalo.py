def collect_vocalo_corpus() -> int:
    """ボカロコーパスを tools/corpus/vocalo.jsonl に書き出す"""
    CORPUS_DIR.mkdir(parents=True, exist_ok=True)
    now = datetime.now(timezone.utc).isoformat()
    lines_written = 0

    with open(CORPUS_FILE, "w", encoding="utf-8") as f:
        for item in VOCALO_CLASSIC_CORPUS:
            row = {
                "source": "vocalo_classic",
                "song_title": item["title"],
                "text": item["text"].strip(),
                "fetched_at": now,
            }
            f.write(json.dumps(row, ensure_ascii=False) + "\n")
            lines_written += 1

    print(f"Collected {lines_written} vocalo classic corpus items into {CORPUS_FILE}")
    return lines_written


if __name__ == "__main__":
    collect_vocalo_corpus()

