import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'

// 相対 URL は sw.js の場所を基準に解決するため、ルート・サブディレクトリ共通。
const output = new URL('../.output/public/', import.meta.url)
const offline = await readFile(new URL('offline.html', output))
const index = await readFile(new URL('index.html', output))
const version = createHash('sha256').update(index).update(offline).digest('hex').slice(0, 16)

await writeFile(new URL('sw.js', output), `// Generated by scripts/build-pwa.mjs
const PREFIX = 'floppy-io:' + self.registration.scope + ':'
const CACHE = PREFIX + '${version}'
const OFFLINE = new URL('offline.html', self.registration.scope).href

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.add(new Request(OFFLINE, { cache: 'reload' }))))
  // 更新は既存のタブを閉じてから適用し、編集中の投稿を中断しない。
})

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const keys = await caches.keys()
    await Promise.all(keys.filter((key) => key.startsWith(PREFIX) && key !== CACHE).map((key) => caches.delete(key)))
    await self.clients.claim()
  })())
})

self.addEventListener('fetch', (event) => {
  const request = event.request
  const url = new URL(request.url)
  const scope = new URL(self.registration.scope)
  const path = url.pathname.slice(scope.pathname.length)
  // API・添付・外部リソース・書き込みは介入せず、個人データを保存しない。
  if (request.method !== 'GET' || request.mode !== 'navigate' ||
      url.origin !== scope.origin || !url.pathname.startsWith(scope.pathname) ||
      /^(api|uploads)(\\/|$)/.test(path)) return

  event.respondWith(fetch(request).catch(async () => {
    const cache = await caches.open(CACHE)
    return (await cache.match(OFFLINE)) || Response.error()
  }))
})
`)
console.log(`PWA service worker generated (${version})`)
